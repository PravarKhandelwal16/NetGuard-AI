"""
Pipeline API Routes.
Exposes endpoints to trigger training, inspect status, and query results
from ML_DeepLearning.ipynb and ML_Adaptive_Threshold.ipynb.
"""

from fastapi import APIRouter, HTTPException, BackgroundTasks
from pathlib import Path
from typing import Dict, Any, List, Optional
import pandas as pd
import json

from backend.core.notebook_pipeline import pipeline_engine
from backend.core.autoencoder import service

router = APIRouter(prefix="/pipeline", tags=["Pipeline Execution"])

BASE_DIR = Path(__file__).resolve().parent.parent.parent.parent
OUTPUT_DIR = BASE_DIR / "data" / "model_outputs"
SAMPLES_DIR = BASE_DIR / "data" / "samples"


@router.get("/status")
async def get_pipeline_status():
    """Returns the presence, file size, and timestamp of generated artifacts."""
    artifacts = [
        "deep_autoencoder.pt",
        "preprocessing_pipeline.joblib",
        "random_forest.joblib",
        "xgboost.joblib",
        "decision_tree.joblib",
        "logistic_regression.joblib",
        "isolation_forest.joblib",
        "shared_data.npz",
        "anomaly_scores_val.csv",
        "anomaly_scores_test.csv",
        "attharv_results.csv",
        "ishan_results.csv",
        "final_model_comparison.csv",
        "model_comparison_graph.png",
    ]

    status_map = {}
    for fname in artifacts:
        fpath = OUTPUT_DIR / fname
        if fpath.exists():
            status_map[fname] = {
                "exists": True,
                "size_bytes": fpath.stat().st_size,
                "size_kb": round(fpath.stat().st_size / 1024, 2),
                "modified": fpath.stat().st_mtime,
            }
        else:
            status_map[fname] = {"exists": False}

    return {
        "status": "ready" if (OUTPUT_DIR / "deep_autoencoder.pt").exists() else "not_trained",
        "artifacts": status_map,
        "total_artifacts_found": sum(1 for v in status_map.values() if v.get("exists")),
        "total_expected": len(artifacts),
    }


@router.get("/results")
async def get_pipeline_results():
    """Returns the parsed evaluation tables generated by the notebooks."""
    final_csv = OUTPUT_DIR / "final_model_comparison.csv"
    if not final_csv.exists():
        raise HTTPException(status_code=404, detail="Pipeline comparison results not found. Please run the pipeline first.")

    try:
        final_df = pd.read_csv(final_csv)
        attharv_df = pd.read_csv(OUTPUT_DIR / "attharv_results.csv") if (OUTPUT_DIR / "attharv_results.csv").exists() else None
        ishan_df = pd.read_csv(OUTPUT_DIR / "ishan_results.csv") if (OUTPUT_DIR / "ishan_results.csv").exists() else None

        return {
            "final_comparison": final_df.to_dict(orient="records"),
            "attharv_results": attharv_df.to_dict(orient="records") if attharv_df is not None else [],
            "ishan_results": ishan_df.to_dict(orient="records") if ishan_df is not None else [],
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to read results: {str(e)}")


@router.post("/run")
async def run_pipeline_endpoint(dataset_path: Optional[str] = None):
    """
    Executes the complete machine learning and deep learning training pipeline.
    Re-trains all models, tunes adaptive thresholds, and persists all artifacts.
    """
    target_path = dataset_path or str(SAMPLES_DIR / "cicids_sample_stream.csv")
    if not Path(target_path).exists():
        raise HTTPException(status_code=404, detail=f"Dataset not found at {target_path}")

    try:
        result = pipeline_engine.run_pipeline(target_path)
        # Reload the inference service with the newly generated weights
        service.reload_artifacts()
        return result
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Pipeline execution failed: {str(e)}")
